"""
RewindWatcher Notification Dispatch.

Routes post-mortem results to the appropriate parties via email.
Uses ``smtplib`` with Gmail SMTP (``smtp.gmail.com:587``) and reads
sender credentials from environment variables ``SMTP_USER`` and
``SMTP_APP_PASSWORD``.

Also implements dispatch routing logic based on `root_cause_category`:
- infrastructure → configuration error alert
- source_code → code exception alert with fix recommendation
"""

from __future__ import annotations

import logging
import os
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

from watcher.state import WatcherState

logger = logging.getLogger(__name__)

