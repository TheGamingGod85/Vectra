def send_email(
    recipient: str,
    subject: str,
    html_body: str,
) -> bool:
    """Send an HTML email via Gmail SMTP.

    Reads ``SMTP_USER`` and ``SMTP_APP_PASSWORD`` from environment variables.

    Args:
        recipient: Target email address.
        subject:   Email subject line.
        html_body: Full HTML body content.

    Returns:
        ``True`` if the email was sent successfully, ``False`` otherwise.
    """
    smtp_user = os.environ.get("SMTP_USER", "")
    smtp_password = os.environ.get("SMTP_APP_PASSWORD", "")

    if not smtp_user or not smtp_password:
        logger.warning(
            "SMTP credentials not configured (SMTP_USER / SMTP_APP_PASSWORD). "
            "Printing email to console instead."
        )
        print("\n" + "=" * 72)
        print(f"📧  TO:      {recipient}")
        print(f"📧  SUBJECT: {subject}")
        print("=" * 72)
        # Strip HTML tags for console output
        import re
        plain = re.sub(r"<[^>]+>", "", html_body)
        plain = re.sub(r"\n{3,}", "\n\n", plain)
        print(plain.strip())
        print("=" * 72 + "\n")
        return True

    msg = MIMEMultipart("alternative")
    msg["From"] = smtp_user
    msg["To"] = recipient
    msg["Subject"] = subject
    msg.attach(MIMEText(html_body, "html"))

    try:
        with smtplib.SMTP(SMTP_HOST, SMTP_PORT) as server:
            server.ehlo()
            server.starttls()
            server.ehlo()
            server.login(smtp_user, smtp_password)
            server.sendmail(smtp_user, recipient, msg.as_string())

        logger.info("✉️  Email sent to %s — subject: %s", recipient, subject)
        return True
    except Exception as exc:
        logger.error("Failed to send email to %s: %s", recipient, exc)
        return False


def dispatcher_node(state: WatcherState) -> dict:
    """LangGraph node: Notification Dispatcher.

    Routes the post-mortem conclusions to the ``target_email`` based on
    the ``root_cause_category``.
    """
    category = state.get("root_cause_category", "unknown")
    target_email = state["target_email"]

    logger.info(
        "📬 Dispatcher: routing %s alert to %s …",
        category, target_email,
    )

    if category == "infrastructure":
        subject, html_body = _build_infrastructure_email(state)
    else:
        # Covers both 'source_code' and 'unknown'
        subject, html_body = _build_source_code_email(state)

    send_email(target_email, subject, html_body)

    return {}
